#!/usr/bin/env bash
# capture-gateway-env.sh — write the EnvironmentFile openshell-gateway.service
# needs, by reading it off the gateway that is ALREADY RUNNING.
#
# WHY NOT JUST HARDCODE IT. The gateway's whole configuration is environment,
# and every value points into a per-install state directory. Writing a unit from
# a remembered list is how you start a gateway with no driver, no database and
# no TLS material — which binds somewhere else and cuts off every sandbox on the
# box at once. The running process is the only authority on what it needs.
#
# READ-ONLY. This script starts nothing, stops nothing and restarts nothing. It
# reads /proc/<pid>/environ and writes one file. Run it BEFORE installing the
# unit, while the gateway is still up — once it has died there is nothing left
# to read, which is the argument for doing this now rather than during an
# incident.
#
# Usage:
#   sudo ./capture-gateway-env.sh                 # writes /etc/nemoclaw/openshell-gateway.env
#   sudo ./capture-gateway-env.sh --print         # dry run, prints to stdout
set -euo pipefail

OUT="${OUT:-/etc/nemoclaw/openshell-gateway.env}"
PRINT_ONLY=0
[ "${1:-}" = "--print" ] && PRINT_ONLY=1

# comm is truncated to 15 chars by the kernel: "openshell-gatew".
pid="$(pgrep -x openshell-gatew | head -1 || true)"
if [ -z "$pid" ]; then
  echo "no running openshell-gateway found — cannot capture its environment." >&2
  echo "start it the usual way first (nemoclaw <sandbox> gateway restart), then re-run." >&2
  exit 1
fi
echo "reading environment from pid $pid" >&2

# OPENSHELL_* only. HOME/USER/PATH are set by the unit itself, and the systemd
# bookkeeping vars (INVOCATION_ID, JOURNAL_STREAM, SYSTEMD_EXEC_PID) must NOT be
# copied — systemd sets its own, and stale ones confuse journald attribution.
env_block="$(tr '\0' '\n' < "/proc/$pid/environ" | grep '^OPENSHELL' | sort)"
if [ -z "$env_block" ]; then
  echo "pid $pid has no OPENSHELL_* variables — is that really the gateway?" >&2
  exit 1
fi

# PATH is carried because the docker driver shells out to the supervisor binary,
# and that lives beside the nvm node install rather than on the default PATH.
path_line="$(tr '\0' '\n' < "/proc/$pid/environ" | grep '^PATH=' || true)"

render() {
  cat <<EOF
# Generated by capture-gateway-env.sh from the running gateway (pid $pid)
# on $(date -u +%FT%TZ). Regenerate rather than hand-edit: every path below
# points into a per-install state directory and differs between boxes.
#
# No secrets here — the TLS and JWT material is referenced by PATH, not value
# (see OPENSHELL_GATEWAY_CONFIG's toml). Still 0640 root:root, because the file
# names the database and key locations.
$env_block
${path_line}
EOF
}

if [ "$PRINT_ONLY" = 1 ]; then
  render
  exit 0
fi

install -d -m 0755 "$(dirname "$OUT")"
render > "$OUT.tmp"
chmod 0640 "$OUT.tmp"
mv "$OUT.tmp" "$OUT"
echo "wrote $OUT ($(grep -c '^OPENSHELL' "$OUT") OPENSHELL_* variables)" >&2

cat >&2 <<'NEXT'

Next, in a window — this briefly interrupts every seat on the box:

  sudo install -m 0644 openshell-gateway.service /etc/systemd/system/
  sudo systemctl daemon-reload
  # Adopt the ALREADY-RUNNING process's job: stop it, then start under systemd.
  sudo pkill -x openshell-gatew
  sudo systemctl enable --now openshell-gateway.service

Verify:
  systemctl show openshell-gateway.service -p Restart --value      # -> always
  ss -tlnp | grep 8080     # BOTH 127.0.0.1:8080 and the docker bridge gateway
  docker exec <a sandbox> getent hosts host.openshell.internal     # still resolves
  cat /proc/$(pgrep -x openshell-gatew)/oom_score_adj              # -> -500
  sudo pkill -x openshell-gatew && sleep 15 && systemctl is-active openshell-gateway

The bind check is the one that matters: if only 127.0.0.1 is listening, the
sandboxes cannot reach it and the box is down. Roll back by killing the unit and
running `nemoclaw <sandbox> gateway restart` the old way.
NEXT
